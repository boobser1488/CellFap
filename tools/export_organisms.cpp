// Writes the dypt organisms (organisms.dll) as C++ data for builds without the DLL (Android):
//   export_organisms <out.inc>
// The file defines kEmbeddedOrganisms[] = {name, description, genome text}; src/sim/scripted.cpp includes it when
// CELLFAP_EMBEDDED_ORGANISMS is defined.
#include "sim/scripted.hpp"
#include "sim/serialize.hpp"

#include <cstdio>
#include <fstream>
#include <sstream>
#include <string>

static std::string raw(const std::string& s) { return "R\"CFAPRAW(" + s + ")CFAPRAW\""; }

int main(int argc, char** argv) {
    if (argc < 2) {
        std::fprintf(stderr, "usage: export_organisms <out.inc>\n");
        return 2;
    }
    const auto& list = scriptedOrganisms();
    if (list.empty()) {
        std::fprintf(stderr, "%s\n", scriptedStatus().c_str());
        return 1;
    }
    std::string tmp = std::string(argv[1]) + ".tmp.genome.txt";
    std::ostringstream out;
    out << "// Generated by tools/export_organisms from scripts/organisms.dpt — do not edit.\n";
    out << "static const char* const kEmbeddedOrganisms[][3] = {\n";
    for (const ScriptedOrganism& o : list) {
        if (!saveGenome(o.genome, tmp)) return 1;
        std::ifstream f(tmp, std::ios::binary);
        std::stringstream text;
        text << f.rdbuf();
        out << "    {" << raw(o.name) << ",\n     " << raw(o.description) << ",\n     " << raw(text.str()) << "},\n";
    }
    out << "};\n";
    std::remove(tmp.c_str());
    FILE* f = openFileUtf8(argv[1], "wb");
    if (!f) return 1;
    std::string s = out.str();
    std::fwrite(s.data(), 1, s.size(), f);
    std::fclose(f);
    std::printf("%zu organisms -> %s\n", list.size(), argv[1]);
    return 0;
}
